/**
 * Shared HTML escaping utility for all print, PDF, and badge HTML builders.
 * Escapes &, <, >, ", and ' and returns '' for null or undefined.
 */
export function escapeHtml(value: unknown): string {
  if (value === null || value === undefined) return '';
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
